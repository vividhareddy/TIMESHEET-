/**
 * Excel (.xlsx) and PDF exports of the Reports & Analytics data.
 * Both formats render the same sections; the libraries are loaded on demand so they stay out of the main bundle.
 */

export type ExportCellType = 'text' | 'hours' | 'number' | 'percent' | 'date';

export interface ExportColumn {
  header: string;
  type?: ExportCellType;
}

export type ExportCell = string | number | null;

export interface ExportSection {
  /** Heading in the PDF and the first line of the sheet. */
  title: string;
  /** Excel sheet name (shortened and cleaned automatically). */
  sheet: string;
  description?: string;
  columns: ExportColumn[];
  rows: ExportCell[][];
}

export interface ExportMeta {
  title: string;
  organisation: string;
  period: string;
  scope: string;
  generatedBy: string;
}

const BRAND = '1E3A5F';

function saveBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

const formatCell = (value: ExportCell, type: ExportCellType = 'text'): string => {
  if (value === null || value === '') return '—';
  if (type === 'date' && typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value)) {
    return new Date(`${value}T00:00:00`).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' });
  }
  if (typeof value === 'number') {
    if (type === 'hours') return `${Number.isInteger(value) ? value : value.toFixed(1)} h`;
    if (type === 'percent') return `${value}%`;
    return String(value);
  }
  return value;
};

/** Excel sheet names: max 31 characters, no []:*?/\ and unique within the workbook. */
function sheetName(name: string, used: Set<string>): string {
  const base = name.replace(/[[\]:*?/\\]/g, ' ').trim().slice(0, 31) || 'Sheet';
  let candidate = base;
  for (let i = 2; used.has(candidate.toLowerCase()); i++) candidate = `${base.slice(0, 28)} ${i}`;
  used.add(candidate.toLowerCase());
  return candidate;
}

export async function exportExcel(meta: ExportMeta, sections: ExportSection[], filename: string): Promise<void> {
  const { default: ExcelJS } = await import('exceljs');
  const wb = new ExcelJS.Workbook();
  wb.creator = meta.generatedBy;
  wb.created = new Date();
  const used = new Set<string>();

  // Cover sheet with the report context.
  const cover = wb.addWorksheet(sheetName('Summary', used));
  cover.columns = [{ width: 24 }, { width: 70 }];
  cover.addRow([meta.title]).font = { bold: true, size: 16, color: { argb: `FF${BRAND}` } };
  cover.addRow([]);
  for (const [k, v] of [
    ['Organisation', meta.organisation],
    ['Period', meta.period],
    ['Scope', meta.scope],
    ['Generated by', meta.generatedBy],
    ['Generated on', new Date().toLocaleString()],
  ]) {
    const row = cover.addRow([k, v]);
    row.getCell(1).font = { bold: true };
  }
  cover.addRow([]);
  cover.addRow(['Sheets']).font = { bold: true };
  for (const s of sections) cover.addRow([s.sheet, s.description ?? s.title]);

  for (const s of sections) {
    const ws = wb.addWorksheet(sheetName(s.sheet, used), { views: [{ state: 'frozen', ySplit: 3 }] });
    ws.addRow([s.title]).font = { bold: true, size: 13, color: { argb: `FF${BRAND}` } };
    ws.addRow([s.description ?? '']).font = { italic: true, color: { argb: 'FF64748B' } };
    const header = ws.addRow(s.columns.map((c) => c.header));
    header.eachCell((cell) => {
      cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: `FF${BRAND}` } };
      cell.alignment = { vertical: 'middle' };
    });
    if (s.rows.length === 0) {
      ws.addRow(['No data for this period.']).font = { italic: true, color: { argb: 'FF64748B' } };
    }
    for (const r of s.rows) {
      // Excel dates are written as UTC; build them at UTC midnight so no timezone moves them to the previous day.
      const row = ws.addRow(r.map((v, i) => (s.columns[i]?.type === 'date' && typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v) ? new Date(`${v}T00:00:00Z`) : v)));
      s.columns.forEach((c, i) => {
        const cell = row.getCell(i + 1);
        if (c.type === 'hours') cell.numFmt = '0.0#';
        else if (c.type === 'percent') cell.numFmt = '0"%"';
        else if (c.type === 'date') cell.numFmt = 'dd mmm yyyy';
      });
    }
    if (s.rows.length) ws.autoFilter = { from: { row: 3, column: 1 }, to: { row: 3, column: s.columns.length } };
    s.columns.forEach((c, i) => {
      const longest = Math.max(c.header.length, ...s.rows.map((r) => formatCell(r[i] ?? null, c.type).length));
      ws.getColumn(i + 1).width = Math.min(60, Math.max(10, longest + 2));
    });
  }

  const buffer = await wb.xlsx.writeBuffer();
  saveBlob(new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }), filename);
}

export async function exportPdf(meta: ExportMeta, sections: ExportSection[], filename: string): Promise<void> {
  const [{ jsPDF }, { autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  const margin = 36;
  const pageWidth = doc.internal.pageSize.getWidth();
  const lastY = () => (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? margin;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(30, 58, 95);
  doc.text(meta.title, margin, margin + 8);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(71, 85, 105);
  doc.text(`${meta.organisation}  ·  ${meta.period}  ·  ${meta.scope}`, margin, margin + 26);
  doc.text(`Generated by ${meta.generatedBy} on ${new Date().toLocaleString()}`, margin, margin + 40);
  let y = margin + 64;

  for (const s of sections) {
    // Start a section on a new page when its heading and a few rows would not fit.
    if (y > doc.internal.pageSize.getHeight() - 120) {
      doc.addPage();
      y = margin;
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(30, 58, 95);
    doc.text(s.title, margin, y);
    y += 6;
    if (s.description) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(100, 116, 139);
      const lines = doc.splitTextToSize(s.description, pageWidth - margin * 2) as string[];
      doc.text(lines, margin, y + 10);
      y += 10 * lines.length + 2;
    }
    const numeric = new Set(s.columns.map((c, i) => (c.type && c.type !== 'text' && c.type !== 'date' ? i : -1)).filter((i) => i >= 0));
    autoTable(doc, {
      startY: y + 4,
      margin: { left: margin, right: margin },
      head: [s.columns.map((c) => c.header)],
      body: s.rows.length ? s.rows.map((r) => r.map((v, i) => formatCell(v, s.columns[i]?.type))) : [[{ content: 'No data for this period.', colSpan: s.columns.length }]],
      styles: { font: 'helvetica', fontSize: 8, cellPadding: 4, overflow: 'linebreak' },
      headStyles: { fillColor: [30, 58, 95], textColor: 255, fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [248, 250, 252] },
      // Right-align numeric columns, headings included, so each heading sits over its numbers.
      didParseCell: (data) => {
        if (numeric.has(data.column.index) && !(data.cell.raw && typeof data.cell.raw === 'object' && 'colSpan' in data.cell.raw)) {
          data.cell.styles.halign = 'right';
        }
      },
    });
    y = lastY() + 28;
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`${meta.title} · page ${i} of ${pages}`, pageWidth - margin, doc.internal.pageSize.getHeight() - 16, { align: 'right' });
  }
  saveBlob(doc.output('blob'), filename);
}
